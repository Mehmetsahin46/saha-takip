-- 12. PROJELER TABLOSU (MİMARİ PLANLAR)
CREATE TABLE IF NOT EXISTS public.projeler (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lokasyon TEXT NOT NULL,
    baslik TEXT NOT NULL,
    resim_url TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 13. PROJE NOTLARI & HATA PİNLERİ
CREATE TABLE IF NOT EXISTS public.proje_notlari (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proje_id BIGINT REFERENCES public.projeler(id) ON DELETE CASCADE,
    x NUMERIC(6, 3) NOT NULL,
    y NUMERIC(6, 3) NOT NULL,
    aciklama TEXT NOT NULL,
    durum TEXT NOT NULL DEFAULT 'Açık' CHECK (durum IN ('Açık', 'Çözüldü')),
    olusturan TEXT NOT NULL,
    cozen TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 14. TEKLİFLER TABLOSU
CREATE TABLE IF NOT EXISTS public.teklifler (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lokasyon TEXT NOT NULL,
    toplam_maliyet NUMERIC(12, 2) NOT NULL,
    teklif_metni TEXT NOT NULL,
    durum TEXT NOT NULL DEFAULT 'Onay Bekliyor' CHECK (durum IN ('Onay Bekliyor', 'Onaylandı', 'Reddedildi')),
    tarih TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 15. SİSTEM AYARLARI TABLOSU
CREATE TABLE IF NOT EXISTS public.sistem_ayarlari (
    id INTEGER PRIMARY KEY,
    konum_dogrulama_aktif BOOLEAN DEFAULT FALSE,
    qr_dogrulama_aktif BOOLEAN DEFAULT FALSE,
    gunluk_rapor_aktif BOOLEAN DEFAULT FALSE,
    haftalik_rapor_aktif BOOLEAN DEFAULT FALSE,
    aylik_rapor_aktif BOOLEAN DEFAULT FALSE,
    rapor_eposta TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

