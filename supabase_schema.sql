-- ==============================================================================
-- SAHA TAKİP VE ŞANTİYE YÖNETİM SİSTEMİ - SUPABASE VERİTABANI ŞEMASI
-- ==============================================================================

-- 1. PERSONEL TABLOSU
CREATE TABLE IF NOT EXISTS public.personel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personel_no TEXT UNIQUE NOT NULL,
    sifre TEXT NOT NULL,
    ad TEXT NOT NULL,
    rol TEXT NOT NULL CHECK (rol IN ('patron', 'formen', 'personel')),
    gunluk_ucret NUMERIC(10, 2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. LOKASYONLAR (ŞANTİYELER) TABLOSU
CREATE TABLE IF NOT EXISTS public.lokasyonlar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad TEXT UNIQUE NOT NULL,
    enlem NUMERIC(10, 7),
    boylam NUMERIC(10, 7),
    yaricap_metre INTEGER DEFAULT 150,
    qr_kodu TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. GİRİŞ-ÇIKIŞ (MESAİ KAYITLARI) TABLOSU
CREATE TABLE IF NOT EXISTS public.giris_cikis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personel_no TEXT NOT NULL,
    ad TEXT NOT NULL,
    lokasyon TEXT NOT NULL,
    giris_saati TIMESTAMPTZ NOT NULL,
    cikis_saati TIMESTAMPTZ,
    sure_saat NUMERIC(6, 2),
    durum TEXT NOT NULL DEFAULT 'Açık' CHECK (durum IN ('Açık', 'Kapalı')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. MANUEL PUANTAJ DÜZELTMELERİ
CREATE TABLE IF NOT EXISTS public.puantaj_manuel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personel_no TEXT NOT NULL,
    tarih DATE NOT NULL,
    deger TEXT NOT NULL CHECK (deger IN ('1', '0.5', 'P', 'R', 'I')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT puantaj_manuel_personel_tarih_unique UNIQUE (personel_no, tarih)
);

-- 5. AYLIK FAZLA MESAİ SAATLERİ
CREATE TABLE IF NOT EXISTS public.aylik_fazla_mesai (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personel_no TEXT NOT NULL,
    yil INTEGER NOT NULL,
    ay INTEGER NOT NULL CHECK (ay BETWEEN 1 AND 12),
    saat NUMERIC(6, 2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT aylik_fazla_mesai_unique UNIQUE (personel_no, yil, ay)
);

-- 6. SAHA VERİLERİ (HARCAMA / AVANS / FİŞLER)
CREATE TABLE IF NOT EXISTS public.saha_verileri (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personel_no TEXT NOT NULL,
    ad TEXT NOT NULL,
    lokasyon TEXT NOT NULL,
    kalem_turu TEXT NOT NULL,
    miktar NUMERIC(10, 2) NOT NULL,
    birim_fiyat NUMERIC(10, 2) NOT NULL,
    para_birimi TEXT DEFAULT 'PLN',
    toplam NUMERIC(10, 2) NOT NULL,
    aciklama TEXT,
    islem_turu TEXT NOT NULL DEFAULT 'harcama' CHECK (islem_turu IN ('harcama', 'avans')),
    fis_no TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. KALEM TÜRLERİ
CREATE TABLE IF NOT EXISTS public.kalem_turleri (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. ARAÇLAR TABLOSU
CREATE TABLE IF NOT EXISTS public.araclar (
    plaka TEXT PRIMARY KEY,
    marka TEXT,
    model TEXT,
    durum TEXT NOT NULL DEFAULT 'Boşta' CHECK (durum IN ('Boşta', 'Kullanımda', 'Bakımda')),
    son_km NUMERIC(10, 1) DEFAULT 0,
    resim_url TEXT,
    son_muayene_tarihi DATE,
    sonraki_muayene_tarihi DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. ARAÇ KULLANIM GEÇMİŞİ
CREATE TABLE IF NOT EXISTS public.arac_kullanim (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personel_no TEXT NOT NULL,
    ad TEXT NOT NULL,
    plaka TEXT NOT NULL,
    alis_km NUMERIC(10, 1) NOT NULL,
    teslim_km NUMERIC(10, 1),
    katedilen_km NUMERIC(10, 1),
    durum TEXT NOT NULL DEFAULT 'Açık' CHECK (durum IN ('Açık', 'Kapalı')),
    tarih TIMESTAMPTZ DEFAULT NOW(),
    teslim_saati TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. GÖREVLER TABLOSU
CREATE TABLE IF NOT EXISTS public.gorevler (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lokasyon TEXT NOT NULL,
    baslik TEXT NOT NULL,
    aciklama TEXT,
    oncelik TEXT NOT NULL DEFAULT 'Normal' CHECK (oncelik IN ('Düşük', 'Normal', 'Yüksek', 'Acil')),
    son_tarih DATE,
    atanan_personel_no JSONB DEFAULT '[]'::jsonb,
    atanan_adlar JSONB DEFAULT '[]'::jsonb,
    durum TEXT NOT NULL DEFAULT 'Bekliyor' CHECK (durum IN ('Bekliyor', 'Devam Ediyor', 'Tamamlandı')),
    olusturulma_tarihi TIMESTAMPTZ DEFAULT NOW(),
    tamamlanma_tarihi TIMESTAMPTZ,
    tamamlanma_foto_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. ŞANTİYE DEFTERLERİ (GÜNLÜK FAALİYET RAPORLARI)
CREATE TABLE IF NOT EXISTS public.santiye_defterleri (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarih DATE DEFAULT CURRENT_DATE,
    saat TEXT,
    lokasyon TEXT NOT NULL,
    formen_no TEXT NOT NULL,
    formen_adi TEXT NOT NULL,
    hava_durumu TEXT DEFAULT 'Güneşli',
    sicaklik TEXT,
    saha_durumu TEXT DEFAULT 'Normal',
    saha_formen_sayisi INTEGER DEFAULT 0,
    saha_usta_sayisi INTEGER DEFAULT 0,
    saha_isci_sayisi INTEGER DEFAULT 0,
    ofis_personel_sayisi INTEGER DEFAULT 0,
    taseron_ekipleri JSONB DEFAULT '[]'::jsonb,
    arac_ekipman JSONB DEFAULT '[]'::jsonb,
    gelen_malzemeler JSONB DEFAULT '[]'::jsonb,
    bugun_yapilan TEXT NOT NULL,
    yarin_yapilacak TEXT,
    isg_durumu TEXT DEFAULT 'Kazasız Gün',
    isg_toolbox BOOLEAN DEFAULT true,
    isg_notlari TEXT,
    engeller_gecikmeler TEXT,
    notlar TEXT,
    fotograflar JSONB DEFAULT '[]'::jsonb,
    patron_onay TEXT DEFAULT 'Yeni' CHECK (patron_onay IN ('Yeni', 'Görüldü', 'Onaylandı', 'Revize İstendi')),
    patron_notu TEXT,
    patron_yarin_notu TEXT,
    durum TEXT NOT NULL DEFAULT 'Yeni' CHECK (durum IN ('Yeni', 'Görüldü')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

