const LocaleContext = createContext({
  locale: 'tr',
  setLocale: () => {},
  t: (k) => k,
  aylar: sozluk.tr.aylar,
  haftaGunleri: sozluk.tr.haftaGunleri,
  sureFormatlaLocale: (saatOndalik) => '',
  formatRol: (rol) => rol,
  formatIzinTuru: (tur) => tur,
});

export function LocaleProvider({ children }) {
  const [locale, setLocaleState] = useState('tr');

  useEffect(() => {
    const saved = localStorage.getItem('appLocale');
    if (saved && (saved === 'tr' || saved === 'pl' || saved === 'en')) {
      setLocaleState(saved);
    }
  }, []);

  const setLocale = (l) => {
    setLocaleState(l);
    localStorage.setItem('appLocale', l);
  };

  const t = (anahtar) => {
    if (sozluk[locale] && sozluk[locale][anahtar]) {
      return sozluk[locale][anahtar];
    }
    if (sozluk['tr'] && sozluk['tr'][anahtar]) {
      return sozluk['tr'][anahtar];
    }
    return anahtar;
  };

  const aylar = sozluk[locale]?.aylar || sozluk.tr.aylar;
  const haftaGunleri = sozluk[locale]?.haftaGunleri || sozluk.tr.haftaGunleri;

  const sureFormatlaLocale = (saatOndalik) => {
    const toplamDakika = Math.round((Number(saatOndalik) || 0) * 60);
    const saat = Math.floor(toplamDakika / 60);
    const dakika = toplamDakika % 60;
    
    if (locale === 'pl') {
      if (saat === 0) return dakika + ' min';
      if (dakika === 0) return saat + ' godz.';
      return saat + ' godz. ' + dakika + ' min';
    } else if (locale === 'en') {
      if (saat === 0) return dakika + ' mins';
      if (dakika === 0) return saat + ' hrs';
      return saat + ' hrs ' + dakika + ' mins';
    } else {
      if (saat === 0) return dakika + ' dk';
      if (dakika === 0) return saat + ' sa';
      return saat + ' sa ' + dakika + ' dk';
    }
  };

  const formatRol = (rol) => {
    if (rol === 'patron') return locale === 'pl' ? 'Właściciel / Szef' : (locale === 'en' ? 'Admin / Owner' : 'Patron');
    if (rol === 'formen') return locale === 'pl' ? '⭐ Majster' : (locale === 'en' ? '⭐ Foreman' : '⭐ Formen');
    if (rol === 'usta') return locale === 'pl' ? '🔧 Fachowiec' : (locale === 'en' ? '🔧 Specialist' : '🔧 Usta');
    return locale === 'pl' ? '👷 Pracownik' : (locale === 'en' ? '👷 Worker' : '👷 Personel');
  };

  const formatIzinTuru = (tur) => {
    const str = String(tur || '');
    if (str.includes('Yıllık') || str.includes('Urlop')) return t('yillikIzin');
    if (str.includes('Mazeret')) return t('mazeretIzni');
    if (str.includes('Rapor') || str.includes('Hastalık') || str.includes('L4')) return t('hastalikRapor');
    if (str.includes('Ücretsiz') || str.includes('Bezpłatny')) return t('ucretsizIzin');
    return str;
  };

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t, aylar, haftaGunleri, sureFormatlaLocale, formatRol, formatIzinTuru }}>
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  const ctx = useContext(LocaleContext);
  if (!ctx) {
    return {
      locale: 'tr',
      setLocale: () => {},
      t: (k) => (sozluk['tr'] && sozluk['tr'][k] ? sozluk['tr'][k] : k),
      aylar: sozluk.tr.aylar,
      haftaGunleri: sozluk.tr.haftaGunleri,
      sureFormatlaLocale: (s) => s + ' sa',
      formatRol: (r) => r,
      formatIzinTuru: (t) => t,
    };
  }
  return ctx;
}
