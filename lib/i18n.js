const LocaleContext = createContext({
  locale: 'tr',
  setLocale: () => {},
  t: (k) => k,
});

export function LocaleProvider({ children }) {
  const [locale, setLocaleState] = useState('tr');

  useEffect(() => {
    const saved = localStorage.getItem('appLocale');
    if (saved && (saved === 'tr' || saved === 'pl' || saved === 'en')) {
      setLocaleState(saved);
    }
  }, []);

  const setLocale = (l) => {
    setLocaleState(l);
    localStorage.setItem('appLocale', l);
  };

  const t = (anahtar) => {
    if (sozluk[locale] && sozluk[locale][anahtar]) {
      return sozluk[locale][anahtar];
    }
    if (sozluk['tr'] && sozluk['tr'][anahtar]) {
      return sozluk['tr'][anahtar];
    }
    return anahtar;
  };

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale() {
  const ctx = useContext(LocaleContext);
  if (!ctx) {
    return {
      locale: 'tr',
      setLocale: () => {},
      t: (k) => (sozluk['tr'] && sozluk['tr'][k] ? sozluk['tr'][k] : k),
    };
  }
  return ctx;
}
